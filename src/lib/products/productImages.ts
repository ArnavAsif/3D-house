/**
 * Resolves the display image URL for a product dynamically:
 * 1. Checks if images exist from Supabase.
 * 2. If not or if local relative path, looks up curated fallback.
 */
export function getProductDisplayImageUrl(product: {
  id?: string;
  showroomId?: string;
  slug?: string;
  images?: Array<{ imageUrl?: string }>;
}): string {
  if (product.images && product.images.length > 0) {
    const first = product.images[0]?.imageUrl;
    if (first && first.startsWith('http')) return first;
  }

  // Lookup in curated catalog
  const keys = [product.id, product.showroomId, product.slug].filter(Boolean) as string[];
  for (const k of keys) {
    if (CURATED_PRODUCT_IMAGES[k]) {
      return CURATED_PRODUCT_IMAGES[k];
    }
  }

  // Generic luxury architectural interior fallback
  return 'https://images.unsplash.com/photo-1600210492486-724fe5c67fb0?auto=format&fit=crop&w=1000&q=85';
}
